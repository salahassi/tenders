function tableModel(key: string): RenderModel {
  const [language, policy] = key.split("-");
  return {
    id: "synthetic-native-table",
    version: 1,
    mode: "draft",
    volume: "combined",
    language,
    placeholder_version:
      policy === "legacy" ? undefined : (Number(policy) as 1 | 2),
    created_at: "2026-11-04T00:00:00Z",
    footer: "Draft",
    blocks: [
      { type: "title", text: "Native tables" },
      { type: "toc", text: "Contents" },
      { type: "heading", text: "Scope" },
      {
        type: "table",
        headers: ["A & <B>", "رقم 1", "Empty"],
        rows: [
          ["\"quoted\" and 'literal'", "اختبار API v2", ""],
          ["[INPUT REQUIRED: witness]", "[مطلوب: الموعد]", "0"],
        ],
      },
      {
        type: "table",
        headers: ["Label", "Value"],
        rows: [
          ["AA", "BB"],
          ["CC", "DD"],
        ],
      },
    ],
  };
}
it.each(Object.entries(golden))(
  "preserves every native document XML byte for %s",
  async (key, expected) => {
    const model = tableModel(key);
    const bytes = new Uint8Array(
      await (await renderDocx(model, fonts)).arrayBuffer(),
    );
    const document = unzipSync(bytes)["word/document.xml"];
    expect(createHash("sha256").update(document).digest("hex")).toBe(expected);
    expect(strFromU8(document)).not.toContain("TENDERDESK_TABLE_");
    expect(verifyExportDocx(bytes, model)).toBe(true);
  },
);
