it.each(Object.entries(paragraphGolden))(
  "preserves native paragraphs, bullets and field relationships for %s",
  async (key, expected) => {
    const model = tableModel(key);
    model.blocks.splice(
      3,
      0,
      { type: "paragraph", text: "Source & scope — المصدر API v2" },
      { type: "bullet", text: "First bullet & <literal>" },
      { type: "bullet", text: "ثاني بند 12" },
      { type: "placeholder", text: "[INPUT REQUIRED: date]", gap_id: "date" },
    );
    const bytes = new Uint8Array(
      await (await renderDocx(model, fonts)).arrayBuffer(),
    );
    const files = unzipSync(bytes),
      document = strFromU8(files["word/document.xml"]);
    // docx's counter is global across documents. The frozen old-renderer oracle
    // normalizes only those allocation IDs, then independently checks linkage.
    const normalized = document
      .replace(/_Toc\d+/g, "_TocN")
      .replace(/(<w:bookmark(?:Start|End)\b[^>]* w:id=")\d+/g, "$1N");
    expect(createHash("sha256").update(normalized).digest("hex")).toBe(
      expected,
    );
    const bookmark = document.match(
      /<w:bookmarkStart w:name="([^"]+)" w:id="([^"]+)"/,
    )!;
    expect(bookmark).toBeTruthy();
    expect(document).toContain(`w:anchor="${bookmark[1]}"`);
    expect(document).toContain(`PAGEREF ${bookmark[1]} `);
    expect(document).toContain(`<w:bookmarkEnd w:id="${bookmark[2]}"`);
    const numbering = strFromU8(files["word/numbering.xml"]);
    const references = [...document.matchAll(/<w:numId w:val="([^"]+)"/g)];
    expect(references).toHaveLength(2);
    for (const reference of references)
      expect(numbering).toContain(`<w:num w:numId="${reference[1]}"`);
    expect(verifyExportDocx(bytes, model)).toBe(true);
  },
);
it("retains every ragged row value and pads only missing positions", async () => {
  const model = tableModel("en-2");
  model.blocks = [
    ...model.blocks.slice(0, 3),
    {
      type: "table",
      headers: ["Supplied header"],
      rows: [
        ["First", "Literal <w:ins> & overflow", "[INPUT REQUIRED: witness]"],
        ["Second"],
      ],
    },
  ];
  const bytes = new Uint8Array(
    await (await renderDocx(model, fonts)).arrayBuffer(),
  );
  const document = strFromU8(unzipSync(bytes)["word/document.xml"]);
  expect(document.match(/<w:gridCol\b/g)).toHaveLength(3);
  expect(document.match(/<w:tc>/g)).toHaveLength(9);
  expect(document).toContain("&lt;");
  expect(document).not.toContain("<w:ins>");
  expect(verifyExportDocx(bytes, model)).toBe(true);
});
it("reuses repeated row XML without copying keep-next onto the last row", async () => {
  const model = tableModel("en-1");
  model.blocks = [
    ...model.blocks.slice(0, 3),
    {
      type: "table",
      headers: ["A", "B"],
      rows: [
        ["Same", "Value"],
        ["Same", "Value"],
        ["Same", "Value"],
      ],
    },
  ];
  const bytes = new Uint8Array(
    await (await renderDocx(model, fonts)).arrayBuffer(),
  );
  const rows = [
    ...strFromU8(unzipSync(bytes)["word/document.xml"]).matchAll(
      /<w:tr>[\s\S]*?<\/w:tr>/g,
    ),
  ].map((match) => match[0]);
  expect(rows).toHaveLength(4);
  expect(rows[1]).toBe(rows[2]);
  expect(rows[2].match(/<w:keepNext\/>/g)).toHaveLength(2);
  expect(rows[3].match(/<w:keepNext w:val="false"\/>/g)).toHaveLength(2);
  expect(verifyExportDocx(bytes, model)).toBe(true);
});
it("rejects unsupported raw XML nodes and attribute names", () => {
  expect(() => nativeTableXml({ _raw: "<w:ins/>" })).toThrow();
  expect(() =>
    nativeTableXml({ "w:t": { _attr: { 'injected=">': "x" } } }),
  ).toThrow();
});
it.each([0, 2])(
  "refuses a native table slot appearing %s times",
  async (count) => {
    const marker = "SYNTHETIC_NATIVE_SLOT";
    const skeleton = await Packer.toBlob(
      new Document({
        sections: [
          {
            children: Array.from(
              { length: count },
              () => new Paragraph({ children: [new TextRun(marker)] }),
            ),
          },
        ],
      }),
    );
    await expect(
      packStreamedTables(skeleton, [
        {
          marker,
          *xml() {
            yield "<w:tbl/>";
          },
        },
      ]),
    ).rejects.toThrow("slot");
  },
);
